def is_generated_file(file_path: str) -> bool:
    """Check if a file path matches autogenerated patterns."""
    for pattern in GENERATED_PATTERNS:
        if pattern.search(file_path):
            return True
    return False


def is_lockfile(file_path: str) -> bool:
    """Check if a file is a lockfile."""
    basename = file_path.rsplit("/", 1)[-1].lower() if "/" in file_path else file_path.lower()
    return basename in LOCKFILES


def is_config_file(file_path: str) -> bool:
    """Check if a file is a useful config file (should be kept)."""
    path_lower = file_path.lower()
    basename = path_lower.rsplit("/", 1)[-1] if "/" in path_lower else path_lower
    for pattern in CONFIG_KEEP_PATTERNS:
        if basename.startswith(pattern) or pattern in path_lower:
            return True
    return False


def is_data_file(file_path: str) -> bool:
    """Check if a file is a data/config dump (generally exclude)."""
    ext = PurePosixPath(file_path).suffix.lower()
    if ext in DATA_EXTENSIONS:
        # Exception: keep config files
        return not is_config_file(file_path)
    return False


def compute_alphanumeric_ratio(text: str) -> float:
    """Compute the ratio of alphanumeric characters in text."""
    if not text:
        return 0.0
    alnum = sum(1 for c in text if c.isalnum())
    return alnum / len(text)


def compute_line_stats(text: str) -> Dict[str, Any]:
    """Compute line-level statistics for a code file."""
    lines = text.split("\n")
    num_lines = len(lines)
    max_line_len = max((len(line) for line in lines), default=0)
    avg_line_len = sum(len(line) for line in lines) / max(num_lines, 1)

    # Count blank lines
    blank_lines = sum(1 for line in lines if not line.strip())

    return {
        "num_lines": num_lines,
        "max_line_len": max_line_len,
        "avg_line_len": avg_line_len,
        "blank_line_ratio": blank_lines / max(num_lines, 1),
    }


def filter_code_sample(
    sample: Dict[str, Any],
    config: Dict[str, Any],
    stats: Optional[FilterStats] = None,
) -> Optional[Dict[str, Any]]:
    """Apply all code filtering rules to a sample.

    Args:
        sample: Dict with 'text', 'file_path', 'language', etc.
        config: File filter configuration from dataset_config.yaml.
        stats: Optional FilterStats to record pass/reject.

    Returns:
        The sample if it passes all filters, None otherwise.
    """
    text = sample.get("text", "")
    file_path = sample.get("file_path", "")
    size_bytes = sample.get("size_bytes", len(text.encode("utf-8", errors="replace")))

    file_filters = config.get("file_filters", {})

    # --- Size filters ---
    min_size = file_filters.get("min_file_size_bytes", 100)
    max_size = file_filters.get("max_file_size_bytes", 1_000_000)
    if size_bytes < min_size:
        if stats:
            stats.record_reject("too_small")
        return None
    if size_bytes > max_size:
        if stats:
            stats.record_reject("too_large")
        return None

    # --- Generated file detection ---
    if is_generated_file(file_path):
        if stats:
            stats.record_reject("generated_file")
        return None

    # --- Lockfile detection ---
    if is_lockfile(file_path):
        if stats:
            stats.record_reject("lockfile")
        return None

    # --- Data file detection ---
    if is_data_file(file_path):
        if stats:
            stats.record_reject("data_file")
        return None

    # --- Extension exclusion ---
    ext = PurePosixPath(file_path).suffix.lower()
    exclude_exts = set(file_filters.get("exclude_extensions", []))
    if ext in exclude_exts and not is_config_file(file_path):
        if stats:
            stats.record_reject("excluded_extension")
        return None

    # --- Alphanumeric ratio ---
    min_alnum = file_filters.get("min_alphanumeric_ratio", 0.25)
    alnum_ratio = compute_alphanumeric_ratio(text)
    if alnum_ratio < min_alnum:
        if stats:
            stats.record_reject("low_alphanumeric_ratio")
        return None

    # --- Line stats ---
    line_stats = compute_line_stats(text)
    min_lines = file_filters.get("min_line_count", 3)
    max_lines = file_filters.get("max_line_count", 10000)
    max_line_len = file_filters.get("max_line_length", 1000)

    if line_stats["num_lines"] < min_lines:
        if stats:
            stats.record_reject("too_few_lines")
        return None
    if line_stats["num_lines"] > max_lines:
        if stats:
            stats.record_reject("too_many_lines")
        return None
    if line_stats["max_line_len"] > max_line_len:
        # Check if it's just one or two very long lines (common in minified code)
        long_lines = sum(1 for line in text.split("\n") if len(line) > max_line_len)
        if long_lines > 2:
            if stats:
                stats.record_reject("lines_too_long")
            return None

    # --- Empty/whitespace-only ---
    if not text.strip():
        if stats:
            stats.record_reject("empty")
        return None

    if stats:
        stats.record_pass()

    # Add computed metadata
    sample["alnum_ratio"] = alnum_ratio
    sample["num_lines"] = line_stats["num_lines"]
    return sample


# ==============================================================
# Documentation Filtering
# ==============================================================

def filter_doc_sample(
    sample: Dict[str, Any],
    config: Dict[str, Any],
    lang_detector: Optional[Callable] = None,
    stats: Optional[FilterStats] = None,
) -> Optional[Dict[str, Any]]:
    """Apply documentation filtering rules.

    Args:
        sample: Dict with 'text', 'file_path', etc.
        config: Doc filter configuration.
        lang_detector: Optional callable(text) -> (lang, confidence).
        stats: Optional FilterStats.

    Returns:
        The sample if it passes, None otherwise.
    """
    text = sample.get("text", "")
    doc_filters = config.get("doc_filters", {})

    # --- Length filters ---
    min_len = doc_filters.get("min_length_chars", 200)
    max_len = doc_filters.get("max_length_chars", 500_000)
    if len(text) < min_len:
        if stats:
            stats.record_reject("doc_too_short")
        return None
    if len(text) > max_len:
        if stats:
            stats.record_reject("doc_too_long")
        return None

    # --- Alphanumeric ratio ---
    min_alnum = doc_filters.get("min_alphanumeric_ratio", 0.50)
    alnum_ratio = compute_alphanumeric_ratio(text)
    if alnum_ratio < min_alnum:
        if stats:
            stats.record_reject("doc_low_alnum")
        return None

    # --- Language detection ---
    lang_cfg = doc_filters.get("language_detection", {})
    if lang_cfg.get("enabled", False) and lang_detector is not None:
        min_conf = lang_cfg.get("min_english_confidence", 0.70)
        lang, confidence = lang_detector(text)
        if lang != "en" or confidence < min_conf:
            if stats:
                stats.record_reject("non_english_doc")
            return None

    # --- Boilerplate detection ---
    max_boilerplate = doc_filters.get("max_boilerplate_ratio", 0.4)
    lines = text.split("\n")
    if len(lines) > 5:
        # Simple boilerplate: count repeated lines
        from collections import Counter
        line_counts = Counter(line.strip() for line in lines if line.strip())
        total_lines = sum(line_counts.values())
        repeated = sum(c - 1 for c in line_counts.values() if c > 1)
        if total_lines > 0 and (repeated / total_lines) > max_boilerplate:
            if stats:
                stats.record_reject("doc_boilerplate")
            return None

    if stats:
        stats.record_pass()

    return sample


