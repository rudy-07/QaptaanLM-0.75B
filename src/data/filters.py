# Math Content Filtering
# ==============================================================

def filter_math_sample(
    sample: Dict[str, Any],
    config: Dict[str, Any],
    lang_detector: Optional[Callable] = None,
    stats: Optional[FilterStats] = None,
) -> Optional[Dict[str, Any]]:
    """Apply math content filtering rules.

    Args:
        sample: Dict with 'text', 'url', 'metadata', etc.
        config: Math filter configuration.
        lang_detector: Optional callable(text) -> (lang, confidence).
        stats: Optional FilterStats.

    Returns:
        The sample if it passes, None otherwise.
    """
    text = sample.get("text", "")
    filters = config.get("filters", {})

    # --- Length ---
    min_len = filters.get("min_length_chars", 100)
    max_len = filters.get("max_length_chars", 200_000)
    if len(text) < min_len:
        if stats:
            stats.record_reject("math_too_short")
        return None
    if len(text) > max_len:
        if stats:
            stats.record_reject("math_too_long")
        return None

    math_quality = filters.get("math_quality", {})

    # --- OCR artifacts ---
    if math_quality.get("reject_ocr_artifacts", True):
        if OCR_PATTERNS.search(text):
            if stats:
                stats.record_reject("math_ocr_artifact")
            return None

    # --- Broken LaTeX ---
    if math_quality.get("reject_broken_latex", True):
        # Simple heuristic: check for unmatched $ or \begin without \end
        dollar_count = text.count("$") - text.count("\\$")
        if dollar_count % 2 != 0 and dollar_count > 5:
            if stats:
                stats.record_reject("math_broken_latex")
            return None

        begin_count = text.count("\\begin{")
        end_count = text.count("\\end{")
        if begin_count > 0 and abs(begin_count - end_count) > 2:
            if stats:
                stats.record_reject("math_unmatched_env")
            return None

    # --- Repeated content ---
    max_repeated = math_quality.get("max_repeated_line_ratio", 0.3)
    lines = [line.strip() for line in text.split("\n") if line.strip()]
    if len(lines) > 5:
        from collections import Counter
        line_counts = Counter(lines)
        repeated = sum(c - 1 for c in line_counts.values() if c > 1)
        if repeated / max(len(lines), 1) > max_repeated:
            if stats:
                stats.record_reject("math_repeated_content")
            return None

    # --- Language detection ---
    lang_cfg = filters.get("language_detection", {})
    if lang_cfg.get("enabled", False) and lang_detector is not None:
        min_conf = lang_cfg.get("min_english_confidence", 0.60)
        lang, confidence = lang_detector(text)
        if lang != "en" or confidence < min_conf:
            if stats:
                stats.record_reject("non_english_math")
            return None

    if stats:
        stats.record_pass()

    return sample


