# Web Text Filtering (FineWeb-HQ)
# ==============================================================

def filter_web_sample(
    sample: Dict[str, Any],
    config: Dict[str, Any],
    lang_detector: Optional[Callable] = None,
    stats: Optional[FilterStats] = None,
) -> Optional[Dict[str, Any]]:
    """Apply web text filtering rules.

    Args:
        sample: Dict with 'text', 'url', 'quality_score', etc.
        config: Web filter configuration.
        lang_detector: Optional callable(text) -> (lang, confidence).
        stats: Optional FilterStats.

    Returns:
        The sample if it passes, None otherwise.
    """
    text = sample.get("text", "")
    filters = config.get("filters", {})

    # --- Length ---
    min_len = filters.get("min_length_chars", 200)
    max_len = filters.get("max_length_chars", 200_000)
    if len(text) < min_len:
        if stats:
            stats.record_reject("web_too_short")
        return None
    if len(text) > max_len:
        if stats:
            stats.record_reject("web_too_long")
        return None

    # --- Alphanumeric ratio ---
    min_alnum = filters.get("min_alphanumeric_ratio", 0.60)
    if compute_alphanumeric_ratio(text) < min_alnum:
        if stats:
            stats.record_reject("web_low_alnum")
        return None

    # --- Quality score ---
    min_quality = filters.get("min_quality_score")
    if min_quality is not None:
        score = sample.get("quality_score")
        if score is not None and score < min_quality:
            if stats:
                stats.record_reject("web_low_quality")
            return None

    # --- Language detection ---
    lang_cfg = filters.get("language_detection", {})
    if lang_cfg.get("enabled", False) and lang_detector is not None:
        min_conf = lang_cfg.get("min_english_confidence", 0.80)
        lang, confidence = lang_detector(text)
        if lang != "en" or confidence < min_conf:
            if stats:
                stats.record_reject("non_english_web")
            return None

    # --- Web boilerplate ---
    if filters.get("remove_boilerplate", True):
        text_lower = text.lower()
        boilerplate_count = sum(
            1 for phrase in WEB_BOILERPLATE if phrase in text_lower
        )
        # If too many boilerplate phrases relative to text length
        if boilerplate_count > 3 and boilerplate_count / max(len(text) / 500, 1) > 0.5:
            if stats:
                stats.record_reject("web_boilerplate")
            return None

    if stats:
        stats.record_pass()

    return sample


