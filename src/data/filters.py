# Vault (Function-Level) Filtering
# ==============================================================

def filter_vault_sample(
    sample: Dict[str, Any],
    config: Dict[str, Any],
    stats: Optional[FilterStats] = None,
) -> Optional[Dict[str, Any]]:
    """Apply filtering rules for The Vault function-level code.

    Args:
        sample: Dict with 'text', 'language', 'identifier', etc.
        config: Vault filter configuration.
        stats: Optional FilterStats.

    Returns:
        The sample if it passes, None otherwise.
    """
    text = sample.get("text", "")
    filters = config.get("filters", {})

    # --- Length ---
    min_len = filters.get("min_code_length_chars", 50)
    max_len = filters.get("max_code_length_chars", 50_000)
    if len(text) < min_len:
        if stats:
            stats.record_reject("vault_too_short")
        return None
    if len(text) > max_len:
        if stats:
            stats.record_reject("vault_too_long")
        return None

    # --- Alphanumeric ratio ---
    min_alnum = filters.get("min_alphanumeric_ratio", 0.30)
    if compute_alphanumeric_ratio(text) < min_alnum:
        if stats:
            stats.record_reject("vault_low_alnum")
        return None

    # --- Empty identifier ---
    if not sample.get("identifier", "").strip():
        if stats:
            stats.record_reject("vault_no_identifier")
        return None

    if stats:
        stats.record_pass()

    return sample


