"""Data filtering pipeline for CPT datasets.

Implements multi-signal filtering for:
- Code files (language, extension, size, quality, generated-code detection)
- Documentation (language detection, boilerplate removal, quality)
- Web text (language, quality score, boilerplate)
- Math content (LaTeX validation, OCR artifact detection)
"""

