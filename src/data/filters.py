OCR_PATTERNS = re.compile(
    r"[^\x00-\x7F]{10,}|"  # Long non-ASCII sequences
    r"[\x00-\x08\x0e-\x1f]{3,}|"  # Control characters
    r"(.)\1{10,}|"  # Repeated characters
    r"[|]{5,}"  # Repeated pipes (common OCR artifact)
)


class FilterStats:
    """Track filtering statistics for reporting."""

    def __init__(self):
        self.total_seen = 0
        self.total_passed = 0
        self.reasons: Dict[str, int] = {}

    def record_pass(self):
        self.total_seen += 1
        self.total_passed += 1

    def record_reject(self, reason: str):
        self.total_seen += 1
        self.reasons[reason] = self.reasons.get(reason, 0) + 1

    @property
    def pass_rate(self) -> float:
        if self.total_seen == 0:
            return 0.0
        return self.total_passed / self.total_seen

    def summary(self) -> Dict[str, Any]:
        return {
            "total_seen": self.total_seen,
            "total_passed": self.total_passed,
            "pass_rate": f"{self.pass_rate:.2%}",
            "rejection_reasons": dict(
                sorted(self.reasons.items(), key=lambda x: -x[1])
            ),
        }


