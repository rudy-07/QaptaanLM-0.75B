class LanguageDetector:
    """Lightweight language detector using fastText.

    Falls back to simple heuristics if fastText is not available.
    """

    def __init__(self, model_path: Optional[str] = None):
        """Initialize the language detector.

        Args:
            model_path: Path to fastText lid model. If None, will try
                       to download lid.176.bin automatically.
        """
        self.model = None
        self._load_model(model_path)

    def _load_model(self, model_path: Optional[str] = None):
        """Try to load fastText language detection model."""
        try:
            import fasttext

            if model_path and Path(model_path).exists():
                self.model = fasttext.load_model(model_path)
            else:
                # Try common locations
                for path in [
                    "lid.176.bin",
                    "/tmp/lid.176.bin",
                    Path.home() / ".cache" / "fasttext" / "lid.176.bin",
                ]:
                    if Path(path).exists():
                        self.model = fasttext.load_model(str(path))
                        break

            if self.model is None:
                logger.warning(
                    "fastText lid model not found. Language detection will "
                    "use fallback heuristics. Download lid.176.bin from "
                    "https://dl.fbaipublicfiles.com/fasttext/supervised-models/lid.176.bin"
                )
        except ImportError:
            logger.warning(
                "fastText not installed. Language detection will use "
                "fallback heuristics. Install with: pip install fasttext-wheel"
            )

    def detect(self, text: str) -> Tuple[str, float]:
        """Detect the language of a text.

        Args:
            text: Input text.

        Returns:
            Tuple of (language_code, confidence).
        """
        if not text or len(text.strip()) < 20:
            return ("unknown", 0.0)

        if self.model is not None:
            # fastText expects single-line input
            clean = text.replace("\n", " ")[:5000]
            predictions = self.model.predict(clean, k=1)
            label = predictions[0][0].replace("__label__", "")
            confidence = float(predictions[1][0])
            return (label, confidence)

        # Fallback: simple heuristic based on character distribution
        return self._fallback_detect(text)

    def _fallback_detect(self, text: str) -> Tuple[str, float]:
        """Simple fallback language detection using character analysis."""
        # Count ASCII vs non-ASCII
        ascii_chars = sum(1 for c in text if ord(c) < 128)
        total_chars = len(text)

        if total_chars == 0:
            return ("unknown", 0.0)

        ascii_ratio = ascii_chars / total_chars

        # High ASCII ratio suggests English or code
        if ascii_ratio > 0.95:
            return ("en", 0.7)
        elif ascii_ratio > 0.80:
            return ("en", 0.5)
        else:
            return ("unknown", 0.3)

    def __call__(self, text: str) -> Tuple[str, float]:
        """Convenience: make the detector callable."""
        return self.detect(text)
